#!/usr/bin/env python3
"""Rebuild Atelier/Public/css/atelier.css from the source layers in dev/src.

Usage:  python3 dev/assemble.py
Only needed if you edit the CSS sources; the built file is committed.
"""
import re, pathlib
here = pathlib.Path(__file__).resolve().parent
src = here / 'src'
dest = here.parent / 'Atelier' / 'Public' / 'css' / 'atelier.css'

def mini(css):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    return re.sub(r'[ \t]*\n[ \t]*', '\n', css).strip()

layers = ['light.css', 'dark.css', 'hand.css', 'icons.css', 'extra.css']
out = '/* Atelier - generated by dev/assemble.py, do not edit. */\n'
out += '\n'.join(mini((src / n).read_text()) for n in layers) + '\n'
dest.write_text(out)

depth, bad = 0, False
for ch in re.sub(r'url\("[^"]*"\)', '', out):
    if ch == '{': depth += 1
    elif ch == '}':
        depth -= 1
        bad = bad or depth < 0
print(len(out), 'bytes, brace depth', depth, 'bad' if bad else 'ok')
